// Helper function to return all products across all categories for instant search
export function getAllProducts(): ProductItem[] {
  const seenIds = new Set<string>();
  const list: ProductItem[] = [];

  for (const catId in PRODUCTS_BY_CATEGORY) {
    const products = PRODUCTS_BY_CATEGORY[catId as CategoryId] || [];
    for (const p of products) {
      if (!seenIds.has(p.id)) {
        seenIds.add(p.id);
        list.push(p);
      }
    }
  }
  return list;
}
